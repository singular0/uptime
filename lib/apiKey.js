/**
 * API key of the monitor
 *
 * The monitor sends the `monitor.apiKey` setting with its API calls, as "Authorization: Bearer <apiKey>",
 * and the authentication plugins let in the requests that carry it, whether they come from the monitor
 * or from another API client. The webapp and the monitors that run in other processes need the same key.
 *
 * When the setting is empty, the first plugin that asks for a verifier generates a random key. Only a
 * monitor running in the same process as the webapp knows it, since monitor.js passes it to the monitor.
 */
const crypto = require('crypto');

let generatedKey;

const configuredKey = function(config) {
  return (config.monitor && config.monitor.apiKey) || undefined;
};

// constant-time string comparison
const safeEqual = function(a, b) {
  const bufferA = Buffer.from(String(a));
  const bufferB = Buffer.from(String(b));
  return bufferA.length === bufferB.length && crypto.timingSafeEqual(bufferA, bufferB);
};

/**
 * A function telling whether a request carries the API key, for the authentication plugins.
 * Only uses the node.js request API, so that it also works on the socket.io handshake.
 */
exports.verifier = function(config) {
  let key = configuredKey(config);
  if (!key) {
    generatedKey = generatedKey || crypto.randomBytes(32).toString('base64url');
    key = generatedKey;
  }
  return function(req) {
    const match = /^Bearer\s+(\S+)$/i.exec(req.headers.authorization || '');
    return match !== null && safeEqual(match[1], key);
  };
};

/**
 * The key that the monitor sends: `monitor.apiKey`, or the key generated by the webapp of this process.
 * Undefined when there is neither.
 */
exports.forMonitor = function(config) {
  return configuredKey(config) || generatedKey;
};
